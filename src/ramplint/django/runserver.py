"""``ramplint --runserver``: start the Django project, scan it, stop it.

The server runs with a generated settings module that imports the project's
settings and wraps the template loaders with
:class:`~ramplint.django.SourceMapLoader` - the project's own files are not
changed. This module only starts a process; it does not import Django.
"""

from __future__ import annotations

import os
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path
from types import TracebackType

SETTINGS_MODULE = "ramplint_sourcemap_settings"
#: Seconds to wait for ``runserver`` to answer.
START_TIMEOUT = 60.0
STOP_TIMEOUT = 10.0

_SETTINGS_TEMPLATE = '''\
"""Generated by ramplint --runserver; deleted when the scan ends."""

from {settings} import *  # noqa: F403

from ramplint.django import wrap_template_loaders

TEMPLATES = wrap_template_loaders(TEMPLATES)  # noqa: F405
RAMPLINT_SOURCE_ROOT = {root!r}
'''


class ServerError(Exception):
    """The development server did not start (the message has its output)."""


def free_port() -> int:
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


class DevServer:
    """``python manage.py runserver`` with source maps, as a context manager."""

    def __init__(
        self,
        root: Path,
        settings_module: str,
        python: str | None = None,
        port: int | None = None,
        start_timeout: float = START_TIMEOUT,
    ) -> None:
        self.root = root.resolve()
        self.settings_module = settings_module
        self.python = python or sys.executable
        self.port = port or free_port()
        self.start_timeout = start_timeout
        self._folder: tempfile.TemporaryDirectory[str] | None = None
        self._log: Path | None = None
        self._process: subprocess.Popen[bytes] | None = None

    @property
    def url(self) -> str:
        return f"http://127.0.0.1:{self.port}/"

    @property
    def output(self) -> str:
        """What the server printed so far."""
        if self._log is None or not self._log.is_file():
            return ""
        return self._log.read_text(encoding="utf-8", errors="replace")

    def __enter__(self) -> DevServer:
        self._folder = tempfile.TemporaryDirectory(prefix="ramplint-runserver-")
        folder = Path(self._folder.name)
        (folder / f"{SETTINGS_MODULE}.py").write_text(
            _SETTINGS_TEMPLATE.format(settings=self.settings_module, root=str(self.root)),
            encoding="utf-8",
        )
        self._log = folder / "server.log"
        env = dict(os.environ)
        env["DJANGO_SETTINGS_MODULE"] = SETTINGS_MODULE
        env["PYTHONPATH"] = os.pathsep.join(
            p for p in (str(folder), str(self.root), env.get("PYTHONPATH", "")) if p
        )
        env["PYTHONUNBUFFERED"] = "1"
        command = [
            self.python, "manage.py", "runserver", f"127.0.0.1:{self.port}", "--noreload",
        ]  # fmt: skip
        with open(self._log, "wb") as log:
            self._process = subprocess.Popen(
                command, cwd=self.root, env=env, stdout=log, stderr=subprocess.STDOUT
            )
        try:
            self._wait_until_ready()
        except BaseException:
            self.__exit__(None, None, None)
            raise
        return self

    def _wait_until_ready(self) -> None:
        assert self._process is not None
        deadline = time.monotonic() + self.start_timeout
        while time.monotonic() < deadline:
            if self._process.poll() is not None:
                raise ServerError(f"the server stopped:\n{self.output.strip()}")
            try:
                with urllib.request.urlopen(self.url, timeout=2):
                    return
            except urllib.error.HTTPError:
                return  # it answers, even if / is an error page
            except (urllib.error.URLError, OSError):
                time.sleep(0.2)
        raise ServerError(
            f"the server did not answer within {self.start_timeout:g}s:\n{self.output.strip()}"
        )

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        process = self._process
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(STOP_TIMEOUT)
            except subprocess.TimeoutExpired:  # pragma: no cover - a stuck server
                process.kill()
                process.wait()
        self._process = None
        if self._folder is not None:
            self._folder.cleanup()
            self._folder = None
